#!/usr/bin/env python3
"""Generate ``baseline.json`` from REAL runs of the stack (never edit the file by hand).

    python3 tests/regression/update_baseline.py [--backend BIN] [--seed 12345]

Starts a private simulator + backend on free ports, runs ``full_pipeline`` for every case in
``regression_lib.CASES`` and stores status, per-task values, limits and the component versions.
Additionally runs the NORMAL/1.0.0 case under several *other* simulator seeds and stores the observed
spread per task kind (``seed_spread``) so the documented tolerances can be audited against real noise;
the script exits non-zero if a tolerance is smaller than 4 sigma of that spread.
"""
from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "experiments"))
sys.path.insert(0, str(HERE))

from regression_lib import CASES, SEED, SEQUENCE, TOLERANCES, summarise_run  # noqa: E402
from stack import Stack  # noqa: E402

SPREAD_SEEDS = [1, 2, 3, 4, 5, 6, 7, 8]


def run_case(st: Stack, case: dict) -> dict:
    run = st.run_sequence(SEQUENCE, dut={"profile": case["profile"], "firmware": case["firmware"]}, retries=0, label=f"baseline-{case['key']}")
    out = summarise_run(run)
    out["run_id"] = run["run_id"]
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default=str(ROOT / "backend" / "build" / "measureflow_backend"))
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--out", default=str(HERE / "baseline.json"))
    args = ap.parse_args()

    cases: dict[str, dict] = {}
    with Stack(ROOT, args.backend, seed=args.seed, name="baseline") as st:
        versions = st.versions()
        for case in CASES:
            cases[case["key"]] = run_case(st, case)
            print(f"{case['key']:16s} -> {cases[case['key']]['status']}  counts={cases[case['key']]['counts']}")
        spread_runs = []
    for seed in SPREAD_SEEDS:
        with Stack(ROOT, args.backend, seed=seed, name="spread") as st:
            spread_runs.append(run_case(st, CASES[0]))
    spread: dict[str, dict] = {}
    base = cases["normal_1.0.0"]["tasks"]
    for idx, t in enumerate(base):
        vals = [r["tasks"][idx]["value"] for r in spread_runs] + [t["value"]]
        sd = statistics.stdev(vals)
        spread[f"{idx:02d} {t['test_name']}"] = {"kind": t["kind"], "mean": statistics.fmean(vals), "std": sd,
                                                 "min": min(vals), "max": max(vals), "n": len(vals)}
    problems = []
    for name, s in spread.items():
        rel, ab = TOLERANCES[s["kind"]]
        tol = rel * abs(s["mean"]) + ab
        if tol < 4 * s["std"]:
            problems.append(f"{name}: tolerance {tol:.4g} < 4 sigma ({4 * s['std']:.4g})")
    doc = {
        "description": "Golden regression baseline generated by tests/regression/update_baseline.py from real runs. Do not edit by hand.",
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "sequence": SEQUENCE,
        "simulator_seed": args.seed,
        "versions": {**versions, "numpy": __import__("numpy").__version__, "scipy": __import__("scipy").__version__,
                     "machine": platform.machine()},
        "tolerances": {k: {"relative": v[0], "absolute": v[1]} for k, v in TOLERANCES.items()},
        "tolerance_rule": "|fresh - baseline| <= relative*|baseline| + absolute; statuses, error codes, names, limits exact",
        "seed_spread": {"seeds": SPREAD_SEEDS + [args.seed], "per_task": spread},
        "cases": cases,
    }
    Path(args.out).write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {args.out}")
    if problems:
        print("TOLERANCE AUDIT FAILED:\n  " + "\n  ".join(problems))
        return 2
    print("tolerance audit ok (every tolerance >= 4 sigma of the observed seed spread)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
